'use strict';
/** Artifact export dispatcher: PDF, DOCX, PPTX, XLSX, Markdown, CSV, JSON, delivery pack. */

const { renderPDF } = require('../lib/pdf');
const { renderDOCX } = require('../lib/docx');
const { renderPPTX } = require('../lib/pptx');
const { renderXLSX } = require('../lib/xlsx');
const { zip } = require('../lib/zip');

const MIME = {
  pdf: 'application/pdf',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  pptx: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  md: 'text/markdown; charset=utf-8',
  csv: 'text/csv; charset=utf-8',
  json: 'application/json; charset=utf-8',
  zip: 'application/zip',
};

const slug = (s) => String(s || 'artifact').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 70) || 'artifact';

function markdown(a) {
  const p = a.project || {};
  const lines = [];
  lines.push(`# ${a.title}`);
  if (a.subtitle) lines.push(`_${a.subtitle}_`);
  lines.push('');
  lines.push(`**Workstream:** ${a.functionName}  `);
  lines.push(`**Tier:** ${p.tierLabel || '-'}  |  **Sandbox:** ${p.codename || '-'}  |  **Model:** ${p.modelName || '-'}  |  **Revision:** r${a.revision || 1}  |  **Status:** ${String(a.status || 'draft').toUpperCase()}  `);
  lines.push(`**Generated:** ${new Date(a.createdAt || Date.now()).toLocaleString('en-GB')}`);
  lines.push('');
  if (p.idea) { lines.push(`> **Brief:** ${p.idea}`); lines.push(''); }
  if (a.summary) { lines.push('## Executive summary'); lines.push(''); lines.push(a.summary); lines.push(''); }
  (a.sections || []).forEach((s) => {
    if (!s || !s.type) return;
    if (s.title) { lines.push(`## ${s.title}`); lines.push(''); }
    switch (s.type) {
      case 'kpis':
        lines.push('| Metric | Value |');
        lines.push('| --- | --- |');
        (s.items || []).forEach((i) => lines.push(`| ${i.label} | ${i.value} |`));
        lines.push('');
        break;
      case 'prose': lines.push(s.text); lines.push(''); break;
      case 'bullets': (s.items || []).forEach((i) => lines.push(`- ${typeof i === 'string' ? i : i.label}`)); lines.push(''); break;
      case 'numbered': (s.items || []).forEach((i, idx) => lines.push(`${idx + 1}. ${typeof i === 'string' ? i : i.label}`)); lines.push(''); break;
      case 'table':
        lines.push(`| ${(s.columns || []).join(' | ')} |`);
        lines.push(`| ${(s.columns || []).map(() => '---').join(' | ')} |`);
        (s.rows || []).forEach((r) => lines.push(`| ${(r || []).map((c) => String(c == null ? '' : c).replace(/\|/g, '\\|').replace(/\n/g, ' ')).join(' | ')} |`));
        lines.push('');
        break;
      case 'timeline':
        (s.items || []).forEach((i) => {
          lines.push(`### ${i.phase}${i.weeks ? ' — ' + i.weeks : ''}`);
          if (i.detail) lines.push(i.detail);
          (i.items || []).forEach((x) => lines.push(`- ${x}`));
          lines.push('');
        });
        break;
      case 'bars':
        lines.push('| Measure | Value |');
        lines.push('| --- | --- |');
        (s.items || []).forEach((i) => lines.push(`| ${i.label} | ${i.valueText || i.value} |`));
        lines.push('');
        break;
      case 'callout':
        lines.push(`> **${s.title || 'Note'}**`);
        lines.push(`> ${s.text}`);
        lines.push('');
        break;
      case 'checklist':
        (s.items || []).forEach((i) => {
          const label = typeof i === 'string' ? i : i.label;
          const done = typeof i === 'object' && i.state === 'approved';
          lines.push(`- [${done ? 'x' : ' '}] ${label}`);
        });
        lines.push('');
        break;
      case 'keyvalue':
        (s.items || []).forEach((i) => lines.push(`- **${i.label}:** ${i.value}`));
        lines.push('');
        break;
      default: break;
    }
  });
  if (a.status !== 'approved') {
    lines.push('---');
    lines.push('');
    lines.push('**Human-in-the-loop notice.** This artifact is a draft. It requires named human sign-off before any client commitment, production promotion or commercial decision.');
  }
  lines.push('');
  lines.push(`_Generated by Kiln · ${new Date().getFullYear()} · kiln.studio_`);
  return lines.join('\n');
}

function csv(a) {
  const tables = (a.sections || []).filter((s) => s.type === 'table' && s.columns && s.rows);
  const table = tables.sort((x, y) => (y.rows || []).length - (x.rows || []).length)[0];
  if (!table) {
    return `Metric,Value\n${((a.sections || []).find((s) => s.type === 'kpis')?.items || []).map((i) => `"${String(i.label).replace(/"/g, '""')}","${String(i.value).replace(/"/g, '""')}"`).join('\n')}`;
  }
  const quote = (v) => `"${String(v == null ? '' : v).replace(/"/g, '""').replace(/\n/g, ' ')}"`;
  return [table.columns.map(quote).join(','), ...(table.rows || []).map((r) => r.map(quote).join(','))].join('\n');
}

function exportArtifact(a, format) {
  const base = slug(`${a.project ? a.project.tierLabel + '-' : ''}${a.functionName}-${a.title}`);
  switch (format) {
    case 'pdf': return { buffer: renderPDF(a), mime: MIME.pdf, filename: `${base}.pdf` };
    case 'docx': return { buffer: renderDOCX(a), mime: MIME.docx, filename: `${base}.docx` };
    case 'pptx': return { buffer: renderPPTX(a), mime: MIME.pptx, filename: `${base}.pptx` };
    case 'xlsx': return { buffer: renderXLSX(a), mime: MIME.xlsx, filename: `${base}.xlsx` };
    case 'md': return { buffer: Buffer.from(markdown(a), 'utf8'), mime: MIME.md, filename: `${base}.md` };
    case 'csv': return { buffer: Buffer.from(csv(a), 'utf8'), mime: MIME.csv, filename: `${base}.csv` };
    case 'json': return { buffer: Buffer.from(JSON.stringify(a, null, 2), 'utf8'), mime: MIME.json, filename: `${base}.json` };
    default: throw new Error(`Unsupported format: ${format}`);
  }
}

function deliveryPack(project, artifacts, sandbox, extras = {}) {
  const files = [];
  const latest = [];
  const seen = new Set();
  [...artifacts].sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt)).forEach((a) => {
    if (seen.has(a.functionKey)) return;
    seen.add(a.functionKey);
    latest.push(a);
  });
  latest.sort((a, b) => (a.functionName || '').localeCompare(b.functionName || ''));
  latest.forEach((a, idx) => {
    const prefix = `${String(idx + 1).padStart(2, '0')}-${slug(a.functionName)}`;
    files.push({ name: `artifacts/${prefix}/artifact.json`, data: JSON.stringify(a, null, 2) });
    files.push({ name: `artifacts/${prefix}/artifact.md`, data: markdown(a) });
    files.push({ name: `artifacts/${prefix}/artifact.pdf`, data: renderPDF(a) });
    if (a.formats.includes('docx')) files.push({ name: `artifacts/${prefix}/artifact.docx`, data: renderDOCX(a) });
    if (a.formats.includes('pptx')) files.push({ name: `artifacts/${prefix}/artifact.pptx`, data: renderPPTX(a) });
    if (a.formats.includes('xlsx')) files.push({ name: `artifacts/${prefix}/artifact.xlsx`, data: renderXLSX(a) });
  });
  if (sandbox) {
    sandbox.files.forEach((f) => files.push({ name: `sandbox/${f.path}`, data: f.content }));
  }
  const manifest = [
    `# ${project.name} — delivery pack`,
    '',
    `- Sandbox: ${sandbox ? sandbox.codename : project.codename}`,
    `- Tier: ${project.tierLabel || project.tier}`,
    `- Model: ${project.modelName || project.model}`,
    `- Generated: ${new Date().toISOString()}`,
    `- Artifacts: ${latest.length}`,
    '',
    '## Contents',
    ...latest.map((a, i) => `${i + 1}. ${a.functionName} — ${a.title} [${a.status}]`),
    '',
    '## Review status',
    ...latest.map((a) => `- ${a.functionName}: ${a.status === 'approved' ? `approved by ${a.approvedBy || 'named reviewer'}` : 'DRAFT — approval required'}`),
    '',
    '## Guardrail',
    'No artifact in this pack constitutes a client commitment. Human sign-off is required before release, production promotion or pricing decisions.',
    '',
    'Generated by Kiln · kiln.studio',
  ].join('\n');
  files.push({ name: 'README.md', data: manifest });
  files.push({ name: 'manifest.json', data: JSON.stringify({ project, artifacts: latest.map((a) => ({ id: a.id, functionKey: a.functionKey, title: a.title, status: a.status, revision: a.revision })), generatedAt: new Date().toISOString() }, null, 2) });
  return { buffer: zip(files), mime: MIME.zip, filename: `${slug(project.name)}-delivery-pack.zip` };
}

module.exports = { exportArtifact, deliveryPack, markdown, csv, MIME, slug };
